"""
config.py — TRUSTFUSE Dataset Module Configuration
====================================================
Centralised configuration for ALL dataset sources:
  - DFDC  (Deepfake Detection Challenge sample)
  - FF++  (FaceForensics++)

All values are read from environment variables with safe defaults.
Paths are resolved relative to this file so the module works
regardless of where it is invoked from.

Usage:
    from config import config
    print(config.DFDC.VIDEO_PATH)
    print(config.FF.VIDEO_PATH)
"""

import os
from pathlib import Path
from dotenv import load_dotenv

# ---------------------------------------------------------------------------
# Load .env if present (silently ignored when absent)
# ---------------------------------------------------------------------------
_env_file = Path(__file__).parent / ".env"
load_dotenv(dotenv_path=_env_file, override=False)

# ---------------------------------------------------------------------------
# Absolute base directory (directory that contains this config.py)
# ---------------------------------------------------------------------------
BASE_DIR: Path = Path(__file__).parent.resolve()


# ---------------------------------------------------------------------------
# Shared constants
# ---------------------------------------------------------------------------
LABEL_MAP: dict = {
    "REAL": "REAL",
    "FAKE": "DEEPFAKE",
    # FF++ uses these alternative raw labels
    "ORIGINAL": "REAL",
    "ALTERED": "DEEPFAKE",
    "MANIPULATED": "DEEPFAKE",
    "DEEPFAKE": "DEEPFAKE",   # already normalised input
}

SUPPORTED_RAW_LABELS: set = set(LABEL_MAP.keys())

RANDOM_SEED: int = int(os.environ.get("RANDOM_SEED", "42"))


# ---------------------------------------------------------------------------
# Sub-config: DFDC
# ---------------------------------------------------------------------------
class _DFDCConfig:
    """Configuration block for the DFDC sample dataset."""

    DATASET_PATH: Path = Path(
        os.environ.get("DATASET_PATH", str(BASE_DIR / "dfdc_sample"))
    ).resolve()

    VIDEO_PATH: Path = Path(
        os.environ.get("VIDEO_PATH", str(BASE_DIR / "dfdc_sample" / "videos"))
    ).resolve()

    METADATA_PATH: Path = Path(
        os.environ.get(
            "METADATA_PATH",
            str(BASE_DIR / "dfdc_sample" / "metadata" / "metadata.json"),
        )
    ).resolve()

    MAX_REAL_VIDEOS: int = int(os.environ.get("MAX_REAL_VIDEOS", "50"))
    MAX_FAKE_VIDEOS: int = int(os.environ.get("MAX_FAKE_VIDEOS", "50"))

    DATASET_SOURCE: str = "DFDC"

    def __repr__(self) -> str:
        return (
            f"DFDCConfig(\n"
            f"  DATASET_PATH  = {self.DATASET_PATH}\n"
            f"  VIDEO_PATH    = {self.VIDEO_PATH}\n"
            f"  METADATA_PATH = {self.METADATA_PATH}\n"
            f"  MAX_REAL      = {self.MAX_REAL_VIDEOS}\n"
            f"  MAX_FAKE      = {self.MAX_FAKE_VIDEOS}\n"
            f")"
        )


# ---------------------------------------------------------------------------
# Sub-config: FaceForensics++
# ---------------------------------------------------------------------------
class _FFConfig:
    """
    Configuration block for the FaceForensics++ dataset.

    FF++ directory layout (compressed / c23 quality):

    faceforensics_sample/
    ├── videos/
    │   ├── original/          ← real (pristine) videos
    │   └── manipulated/       ← fake videos (one or more manipulation methods)
    ├── masks/                 ← binary face-swap masks (optional)
    └── metadata/
        └── metadata.json      ← custom lightweight manifest (generated by user
                                  or provided as part of this module)
    """

    DATASET_PATH: Path = Path(
        os.environ.get("FF_DATASET_PATH", str(BASE_DIR / "faceforensics_sample"))
    ).resolve()

    # Root video folder — real and fake are sub-folders inside
    VIDEO_PATH: Path = Path(
        os.environ.get(
            "FF_VIDEO_PATH", str(BASE_DIR / "faceforensics_sample" / "videos")
        )
    ).resolve()

    # Folder for original (REAL) videos
    ORIGINAL_VIDEO_PATH: Path = Path(
        os.environ.get(
            "FF_ORIGINAL_VIDEO_PATH",
            str(BASE_DIR / "faceforensics_sample" / "videos" / "original"),
        )
    ).resolve()

    # Folder for manipulated (FAKE) videos
    MANIPULATED_VIDEO_PATH: Path = Path(
        os.environ.get(
            "FF_MANIPULATED_VIDEO_PATH",
            str(BASE_DIR / "faceforensics_sample" / "videos" / "manipulated"),
        )
    ).resolve()

    # Optional masks folder
    MASKS_PATH: Path = Path(
        os.environ.get(
            "FF_MASKS_PATH", str(BASE_DIR / "faceforensics_sample" / "masks")
        )
    ).resolve()

    METADATA_PATH: Path = Path(
        os.environ.get(
            "FF_METADATA_PATH",
            str(BASE_DIR / "faceforensics_sample" / "metadata" / "metadata.json"),
        )
    ).resolve()

    MAX_REAL_VIDEOS: int = int(os.environ.get("FF_MAX_REAL_VIDEOS", "50"))
    MAX_FAKE_VIDEOS: int = int(os.environ.get("FF_MAX_FAKE_VIDEOS", "50"))

    # Supported FF++ manipulation methods
    MANIPULATION_METHODS: list = [
        "Deepfakes",
        "Face2Face",
        "FaceShifter",
        "FaceSwap",
        "NeuralTextures",
    ]

    DATASET_SOURCE: str = "FaceForensics++"

    def __repr__(self) -> str:
        return (
            f"FFConfig(\n"
            f"  DATASET_PATH          = {self.DATASET_PATH}\n"
            f"  ORIGINAL_VIDEO_PATH   = {self.ORIGINAL_VIDEO_PATH}\n"
            f"  MANIPULATED_VIDEO_PATH= {self.MANIPULATED_VIDEO_PATH}\n"
            f"  MASKS_PATH            = {self.MASKS_PATH}\n"
            f"  METADATA_PATH         = {self.METADATA_PATH}\n"
            f"  MAX_REAL              = {self.MAX_REAL_VIDEOS}\n"
            f"  MAX_FAKE              = {self.MAX_FAKE_VIDEOS}\n"
            f")"
        )


# ---------------------------------------------------------------------------
# Sampler manifest output path (shared)
# ---------------------------------------------------------------------------
SAMPLE_MANIFEST_PATH: Path = BASE_DIR / "sample_manifest.json"


# ---------------------------------------------------------------------------
# Top-level config object
# ---------------------------------------------------------------------------
class _Config:
    """
    Unified configuration holder for the TRUSTFUSE dataset module.

    Access sub-configs with:
        config.DFDC
        config.FF
    """

    BASE_DIR = BASE_DIR
    LABEL_MAP = LABEL_MAP
    SUPPORTED_RAW_LABELS = SUPPORTED_RAW_LABELS
    RANDOM_SEED = RANDOM_SEED
    SAMPLE_MANIFEST_PATH = SAMPLE_MANIFEST_PATH

    DFDC = _DFDCConfig()
    FF = _FFConfig()

    def __repr__(self) -> str:
        return (
            f"TRUSTFUSEConfig(\n"
            f"  BASE_DIR     = {self.BASE_DIR}\n"
            f"  RANDOM_SEED  = {self.RANDOM_SEED}\n"
            f"  DFDC         = {self.DFDC}\n"
            f"  FF           = {self.FF}\n"
            f")"
        )


# Singleton — import this everywhere
config = _Config()
